// The keys EU4 1.37.5 reads for each widget of a `.gui` file, as in cwtools-eu4-config#448
// (`interface/gui_types.cwt`, generated from what eu4.exe 1.37.5 reads): the widgets `guiTypes`
// holds, the keys each widget takes with the kind of value the game reads, and the child widgets
// each container creates. `if_resolution` takes `min_width`, `max_width`, `min_height` and
// `max_height` and then the widget's own keys and children. Keys and enum words compare without
// regard to case, as the game reads them. Converted from that file one to one, except `ignored`:
// the keys an `iconType` and an `instantTextBoxType` read only to log that they do nothing, which
// the .cwt leaves out. A change of those rules is copied here the same way.

/** What the game reads a key's value as. */
export type GuiValueKind =
  /** A word or a quoted string. */
  | 'text'
  /** A sprite name of the playset's `.gfx` files. */
  | 'sprite'
  | 'bool'
  /** An integer; a fraction is cut to its integer part. */
  | 'int'
  | 'float'
  /** `{ x = … y = … }`, two integers. */
  | 'point'
  /** `{ x y step min max }`: each an integer, `N%` or `auto`. */
  | 'position'
  /** `{ width height step min max }`: each an integer, `N%` or `auto`. */
  | 'size'
  /** `{ left right top bottom }`: each an integer, `N%` or `auto`. */
  | 'offset'
  /** `{ 1 1 1 1 }`, bare numbers. */
  | 'floats'
  /** One of {@link GUI_ORIENTATIONS}. */
  | 'orientation'
  /** One of {@link GUI_CONTAINER_ORIENTATIONS}. */
  | 'containerOrientation'
  /** One of {@link GUI_ANIMATIONS}. */
  | 'animation'
  /** One of {@link GUI_TEXT_FORMATS}. */
  | 'textFormat'
  /** One of {@link GUI_VERTICAL_ALIGNMENTS}. */
  | 'verticalAlignment';

export type GuiSchemaName =
  | 'browser'
  | 'button'
  | 'containerWindow'
  | 'curveGraph'
  | 'dialog'
  | 'dropDownBox'
  | 'dropDownMenu'
  | 'editBox'
  | 'extendedScrollbar'
  | 'gridbox'
  | 'icon'
  | 'instantTextBox'
  | 'layout'
  | 'listBox'
  | 'overlappingElementsBox'
  | 'positionType'
  | 'radioButtonGroup'
  | 'scrollbar'
  | 'scrollbargroup'
  | 'textBox'
  | 'textblock'
  | 'window';

export interface GuiSchema {
  /** The keys the widget takes, spelled as the game's token table does, with their value kind. */
  readonly keys: Readonly<Record<string, GuiValueKind>>;
  /** The child widgets it creates, by key, with the schema of each. */
  readonly children: Readonly<Record<string, GuiSchemaName>>;
  /** Whether it takes `if_resolution` blocks. */
  readonly resolution: boolean;
  /** Keys the game reads only to log that they do nothing in this widget. */
  readonly ignored: readonly string[];
}

